/**
 * The mark beside a speaker's name.
 *
 * These are the vendors' own logos, not approximations. Both were taken from
 * Wikimedia Commons, where both are published as public domain -- they fall
 * below the threshold of originality for copyright. Copyright is not the same
 * as trademark: the marks are still Anthropic's and OpenAI's, and are used
 * here only to say which agent is speaking, which is what they are for.
 *
 *   Claude  File:Claude AI logo.svg          (symbol isolated from the lockup)
 *   OpenAI  File:OpenAI logo 2025 (symbol).svg
 *
 * Drawn inline rather than shipped as files so the app carries no binary
 * assets and the marks stay crisp at any size. The path data is verbatim; only
 * the viewBox was tightened to the symbol's bounding box.
 */
export function Mark({
  harness,
  size = 22,
}: {
  harness: HarnessId;
  size?: number;
}): React.ReactElement {
  return harness === "claude" ? (
    <ClaudeMark size={size} />
  ) : (
    <CodexMark size={size} />
  );
}

